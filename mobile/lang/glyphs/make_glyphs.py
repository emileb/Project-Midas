#!/usr/bin/env python3
"""Writes mobile/ge_glyphs_ru.h: Cyrillic for the two fonts, from cyr_gothic.py and cyr_zurich.py.

    make_glyphs.py            write the header
    make_glyphs.py preview    also write preview_gothic.png / preview_zurich.png here

Letters are bytes 0xC0..0xFF (CP1251 А..я). A letter shaped like a Latin one is drawn with that
glyph; the rest are I8 pixels made to match the font (rows padded to 8, as the fonts are).
"""
import os
import sys

import cyr_gothic
import cyr_zurich
from glyphkit import font, lat, png, width, sbl

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "ge_glyphs_ru.h")
LETTERS = [chr(0x410 + i) for i in range(64)]   # А..Я а..я


def twin(fname, kern):
    """A Latin letter with this kerning index, to stand for the glyph as the previous char."""
    for ch in font(fname)[1]:
        if ch['kern'] == kern and ch['c'].isalpha():
            return ch['c']
    return 'H'


def main():
    entries, pixels = [], []
    for mod in (cyr_gothic, cyr_zurich):
        glyphs = mod.build()
        rows = []
        for c in LETTERS:
            if c in mod.ALIAS:
                a = mod.ALIAS[c]
                rows.append("{'%s', '%s', 0, 0, 0, 0, 0}" % (a, a))
                continue
            g = glyphs[c]
            w, h = width(g), len(g['rows'])
            stride = (w + 7) & ~7
            off = len(pixels)
            for r in g['rows']:
                pixels.extend(list(r) + [0] * (stride - len(r)))
            rows.append("{0, '%s', %d, %d, %d, %d, %d}" % (twin(mod.F, g['kern']), g['bl'], h, w, g['kern'], off))
        entries.append((mod.F, rows))

    out = ["// Generated by mobile/lang/glyphs/make_glyphs.py: edit cyr_gothic.py / cyr_zurich.py instead.",
           "// Cyrillic А..я as bytes 0xC0..0xFF for Bank Gothic [0] and Zurich Bold [1]: a Latin",
           "// look-alike (alias), or I8 pixels at offset. twin: a Latin letter with the same kerning.",
           "",
           "struct GeGlyph",
           "{",
           "    char alias, twin;",
           "    signed char baseline;",
           "    unsigned char height, width, kern;",
           "    unsigned short offset;",
           "};",
           "",
           "static const struct GeGlyph sRuGlyphs[2][64] = {"]
    for fname, rows in entries:
        out.append("    { // %s" % fname[4:])
        for i in range(0, 64, 4):
            out.append("        " + ", ".join(rows[i:i + 4]) + ",")
        out.append("    },")
    out.append("};")
    out.append("")
    out.append("static const unsigned char sRuPixels[] __attribute__((aligned(8))) = {")
    for i in range(0, len(pixels), 16):
        out.append("    " + ", ".join("%d" % v for v in pixels[i:i + 16]) + ",")
    out.append("};")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d bytes of glyphs -> %s" % (len(pixels), os.path.normpath(OUT)))

    if len(sys.argv) > 1 and sys.argv[1] == "preview":
        lines = ["".join(LETTERS[:32]), "".join(LETTERS[32:]), "Секретные материалы: Миссия 1",
                 "Найдите и уничтожьте оружие.", "ЖЕЛЕЗНОДОРОЖНЫЙ ЩИТ, ЮЖНАЯ ПЛОТИНА",
                 "Hello Bond, mission objectives"]
        for mod in (cyr_gothic, cyr_zurich):
            glyphs = mod.build()
            glyphs.update({c: lat(mod.F, a) for c, a in mod.ALIAS.items()})
            png(os.path.join(HERE, "preview_%s.png" % mod.__name__[4:]), [(mod.F, glyphs, l) for l in lines], 4)


if __name__ == "__main__":
    main()
