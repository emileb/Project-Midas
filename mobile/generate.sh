#!/bin/sh
# Makes port_buildinfo.h (scripts/port/buildinfo.cmake on desktop) for ndk-build.
# Only rewritten when its contents change, so an unchanged tree does not rebuild.
set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/mobile/generated/port_buildinfo.h"

COUNT="$(git -C "$ROOT" rev-list --count HEAD 2>/dev/null || echo 0)"
COMMIT="$(git -C "$ROOT" rev-parse --short=9 HEAD 2>/dev/null || echo nogit)"
BRANCH="$(git -C "$ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null | tr -cd 'A-Za-z0-9._/+-')"
[ "$BRANCH" = "HEAD" ] && BRANCH=""
DAY="$(date +%Y%m%d)"

mkdir -p "$(dirname "$OUT")"
TMP="$OUT.tmp"
cat > "$TMP" <<EOF
/* generated by mobile/generate.sh - do not edit */
#ifndef PORT_BUILDINFO_H
#define PORT_BUILDINFO_H
#define PORT_BUILD_NUMBER $COUNT
#define PORT_BUILD_DATE   "$DAY"
#define PORT_BUILD_STRING "$COUNT-$DAY"
#define PORT_BUILD_COMMIT "$COMMIT"
#define PORT_BUILD_BRANCH "$BRANCH"
#endif
EOF

if cmp -s "$TMP" "$OUT"; then
    rm -f "$TMP"
else
    mv "$TMP" "$OUT"
fi
