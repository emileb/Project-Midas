#!/usr/bin/env python3
"""Writes mobile/ge_glyphs.h: the letters above ASCII for both fonts, per code page.

    make_glyphs.py            write the header
    make_glyphs.py preview    also write preview_*.png here

Code page 0 (es, fr, de, pt): CP1252 accented letters, Œ œ ¡ ¿ ß (latin.py).
Code page 1 (ru): Cyrillic А..я as 0xC0..0xFF, CP1251 order (cyr_gothic.py, cyr_zurich.py).
A letter shaped like a Latin one is drawn with that glyph (alias); the rest are I8 pixels made to
match the font (rows padded to 8, as the fonts are).
"""
import os
import sys

import cyr_gothic
import cyr_zurich
import latin
from glyphkit import font, lat, png, width

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "ge_glyphs.h")
FONTS = ("fontBankGothic", "fontZurichBold")


def twin(fname, kern):
    """A Latin letter with this kerning index, to stand for the glyph as the previous char."""
    for ch in font(fname)[1]:
        if ch['kern'] == kern and ch['c'].isalpha():
            return ch['c']
    return 'H'


def fit(fname, g, label):
    """Trim faint rows below the line height: text clipped to its line (the watch's menu rows) drops a
    glyph that reaches past it entirely (textRenderGlyph's partial clip draws an empty rect)."""
    br = lat(fname, '[')
    limit = br['bl'] + len(br['rows'])
    rows = list(g['rows'])
    while g['bl'] + len(rows) > limit and max(rows[-1]) < 100:
        rows.pop()
    if g['bl'] + len(rows) > limit:
        raise SystemExit("%s %s reaches row %d, past the line height %d" % (fname, label, g['bl'] + len(rows), limit))
    return dict(g, rows=rows)


def pages():
    """[page][font] -> {byte: glyph or alias char}."""
    lat_pages = [latin.build(f) for f in FONTS]
    cyr = []
    for mod in (cyr_gothic, cyr_zurich):
        g = mod.build()
        g.update(mod.ALIAS)
        cyr.append({0xC0 + i: g[chr(0x410 + i)] for i in range(64)})
    return [lat_pages, cyr]


def main():
    out_pages, pixels = [], []
    for page in pages():
        fonts = []
        for f, glyphs in zip(FONTS, page):
            rows = []
            for b in range(0x80, 0x100):
                g = glyphs.get(b)
                if g is None:
                    rows.append("{0}")
                elif isinstance(g, str):
                    rows.append("{'%s', '%s'}" % (g, g))
                else:
                    g = fit(f, g, "0x%02X" % b)
                    w, h = width(g), len(g['rows'])
                    stride = (w + 7) & ~7
                    off = len(pixels)
                    for r in g['rows']:
                        pixels.extend(list(r) + [0] * (stride - len(r)))
                    rows.append("{0, '%s', %d, %d, %d, %d, %d}" % (twin(f, g['kern']), g['bl'], h, w, g['kern'], off))
            fonts.append((f, rows))
        out_pages.append(fonts)

    out = ["// Generated by mobile/lang/glyphs/make_glyphs.py: edit the glyph sources there instead.",
           "// Bytes 0x80..0xFF per code page ([0] CP1252 accents, [1] Cyrillic) and font ([0] Bank Gothic,",
           "// [1] Zurich Bold): a Latin look-alike (alias), I8 pixels at offset, or {0} (none).",
           "// twin: a Latin letter with the same kerning.",
           "",
           "struct GeGlyph",
           "{",
           "    char alias, twin;",
           "    signed char baseline;",
           "    unsigned char height, width, kern;",
           "    unsigned short offset;",
           "};",
           "",
           "static const struct GeGlyph sLangGlyphs[2][2][128] = {"]
    for name, fonts in zip(("CP1252", "Cyrillic"), out_pages):
        out.append("    { // %s" % name)
        for f, rows in fonts:
            out.append("        { // %s" % f[4:])
            for i in range(0, 128, 4):
                out.append("            " + ", ".join(rows[i:i + 4]) + ",")
            out.append("        },")
        out.append("    },")
    out.append("};")
    out.append("")
    out.append("static const unsigned char sLangPixels[] __attribute__((aligned(8))) = {")
    for i in range(0, len(pixels), 16):
        out.append("    " + ", ".join("%d" % v for v in pixels[i:i + 16]) + ",")
    out.append("};")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d bytes of glyphs -> %s" % (len(pixels), os.path.normpath(OUT)))

    if len(sys.argv) > 1 and sys.argv[1] == "preview":
        samples = [("cp1252", ["ÀÁÂÃÄÅÇÈÉÊËÌÍÎÏÑÒÓÔÕÖÙÚÛÜÝŒ", "àáâãäåçèéêëìíîïñòóôõöùúûüýÿœß",
                               "¿Qué? ¡Sí! Misión cumplida", "Ação não é você, Grüße, être"]),
                   ("cp1251", ["АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ", "абвгдежзийклмнопрстуфхцчшщъыьэюя",
                               "Секретные материалы: Миссия 1"])]
        for pi, (enc, lines) in enumerate(samples):
            for fi, f in enumerate(FONTS):
                glyphs = {}
                for b, g in pages()[pi][fi].items():
                    glyphs[bytes([b]).decode(enc)] = lat(f, g) if isinstance(g, str) else g
                png(os.path.join(HERE, "preview_%s_%s.png" % (enc, f[4:])), [(f, glyphs, l) for l in lines], 4)


if __name__ == "__main__":
    main()
