"""Cyrillic for Bank Gothic (the small font): capitals rows 2..9, small capitals rows 3..9 (bl 3)."""
from glyphkit import art, lat, flip, cols, setrows, hcat

F = "fontBankGothic"
L = lambda c: lat(F, c)

# Same shape as a Latin glyph (Bank Gothic's lowercase are small capitals)
ALIAS = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'З': '3', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C',
    'Т': 'T', 'Х': 'X',
    'а': 'a', 'в': 'b', 'е': 'e', 'к': 'k', 'м': 'm', 'н': 'h', 'о': 'o', 'р': 'p', 'с': 'c', 'т': 't',
    'х': 'x',
}


def build():
    G = {}
    K, N, R, C, O, H = L('K'), L('N'), L('R'), L('C'), L('O'), L('H')
    k0 = H['kern']

    G['Б'] = art(2, """
......
%#****
%:
%*++**
%=:-=#
%:..-%
##**#+
.....
""", k0)
    G['Г'] = art(2, """
......
%#****
%:
%:
%:
%.
#.
.
""", L('F')['kern'])
    G['Д'] = art(2, """
  .....
  +#**%
  *-  %
  #:  %
 .%.  %
.=#...%.
%#****%#
%.    .%
.      .
""", k0)
    G['Ж'] = hcat(flip(cols(K, 1)), cols(K, 0, 1), cols(K, 1), kern=k0)
    G['И'] = flip(N)
    G['Й'] = setrows(flip(N), 0, """
  =  =
  .==.
""")
    G['Л'] = art(2, """
  ......
  +#***%
  *-  -%
  #.  -%
 :#.  -%
-#=   -%
*=    :*
.      .
""", k0)
    G['П'] = art(2, """
.......
%#***#%
%:   -%
%:   -%
%:   -%
%:   -%
*:   :*
.     .
""", k0)
    G['У'] = art(2, """
.     .
*=   -*
-#.  *-
 *= -*
 :#.*-
  =#+
+#*-
...
""", L('Y')['kern'])
    G['Ф'] = art(2, """
   ...
 .+#%#+.
*=  %  =*
%:  %  :%
*=  %  =*
 .+#%#+.
    %
    .
""", k0)
    G['Ц'] = art(2, """
.     .
#:   :#
%:   -%
%:   -%
%:   -%
%-...-%.
+#***#%#
       %
       .
""", k0)
    G['Ч'] = art(2, """
.     .
#:   :#
%:   -%
%-...=%
+#***#%
     -%
     :*
      .
""", k0)
    G['Ш'] = art(2, """
.    .    .
#:   #:   #
%:   %:   %
%:   %:   %
%:   %:   %
%-...%-...%
##***##***#
...........
""", k0)
    G['Щ'] = art(2, """
.    .    .
#:   #:   #
%:   %:   %
%:   %:   %
%:   %:   %
%-...%-...%.
##***##***##
           %
           .
""", k0)
    G['Ь'] = art(2, """
.
#:
%:
%*++**
%=:-=#
%:..-%
##**#+
.....
""", k0)
    G['Ъ'] = art(2, """
..
**#:
  %:
  %*++**
  %=:-=#
  %:..-%
  ##**#+
  .....
""", L('T')['kern'])
    G['Ы'] = art(2, """
.       .
#:      #
%:      %
%*++**  %
%=:-=#  %
%:..-%  %
##**#+  #
.....   .
""", k0)
    G['Э'] = setrows(flip(C), 5, """
  .===%
""")
    G['Ю'] = hcat(cols(H, 0, 1), art(5, "++\n--"), O, kern=k0)
    G['Я'] = flip(R, kern=k0)

    # ---- small capitals (rows 4..8)
    h, n, o, c, r, k = L('h'), L('n'), L('o'), L('c'), L('r'), L('k')
    s0 = h['kern']
    G['б'] = art(3, """
......
%*****
%-
%#++**
%=..-%
******
.....
""", s0)
    G['г'] = art(3, """
.....
#***+
%:
%:
%:
*.
.
""", L('f')['kern'])
    G['д'] = art(3, """
  ....
 .#**%
 :%  %
 +=  %
-%:..%.
%#****#
%     %
.     .
""", s0)
    G['ж'] = hcat(flip(cols(k, 1)), cols(k, 0, 1), cols(k, 1), kern=s0)
    G['з'] = art(3, """
 ....
*****+
.   :%
  ***+
-.  :%
*****+
 ....
""", L('s')['kern'])
    G['и'] = flip(n)
    G['й'] = setrows(flip(n), 1, """
 =  =
 .==.
""")
    G['л'] = art(3, """
  .....
  +#**%
  *-  %
  #.  %
 =#   %
*=.   *
.     .
""", s0)
    G['п'] = art(3, """
......
#****#
%:  :%
%:  :%
%:  :%
*.  :*
.    .
""", s0)
    G['у'] = art(3, """
.    .
*-  :*
=*  +=
 *--*
  =#-
+#*:
...
""", L('y')['kern'])
    G['ф'] = art(3, """
   ...
 =*#%#*=
%:  %  :%
%:  %  :%
 =*#%#*=
    %
    .
""", s0)
    G['ц'] = art(3, """
.    .
#.  :*
%:  :%
%:  :%
%:..:%.
*****%#
      %
      .
""", s0)
    G['ч'] = art(3, """
.    .
#.  :*
%:  :%
+#**#%
    :%
    :*
     .
""", s0)
    G['ш'] = art(3, """
.   .   .
#.  #.  #
%:  %:  %
%:  %:  %
%:..%:..%
*********
.........
""", s0)
    G['щ'] = art(3, """
.   .   .
#.  #.  #
%:  %:  %
%:  %:  %
%:..%:..%.
*********#
         %
         .
""", s0)
    G['ь'] = art(3, """
.
#.
%:
%#++**
%=..-%
******
.....
""", s0)
    G['ъ'] = art(3, """
..
**#.
  %:
  %#++**
  %=..-%
  ******
  .....
""", L('t')['kern'])
    G['ы'] = art(3, """
.      .
#.     #
%:     %
%#++** %
%=..-% %
****** *
.....  .
""", s0)
    G['э'] = setrows(flip(c), 6, """
  ===%
""")
    G['ю'] = hcat(cols(h, 0, 1), art(6, "++"), o, kern=s0)
    G['я'] = flip(r, kern=s0)
    return G
